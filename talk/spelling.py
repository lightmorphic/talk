"""American to British spelling, for dictating in English.

The speech model knows languages, not countries: there is one English
and it was trained mostly on American text, so it spells the American
way whatever your accent. This is the list that puts it right, applied
to the transcript after the fact.

Every entry has to be safe in every sentence, which rules out a whole
class of words a spelling list would normally carry. "Check" is a
cheque only sometimes; "practice" is the noun in both countries;
"program" stays a program on a computer; "tire", "curb", "draft",
"story" and "disk" all mean something of their own. Those are left
alone rather than corrected wrongly, and so are the pairs where both
spellings are good British English - burned and burnt, yogurt, enquiry,
medieval, fetus.

Most of the list is built rather than typed, from a stem and the
endings that stem really takes. Building can invent a word nobody says
- "colourful" is wanted, "colourable" is not - and that costs nothing,
because a key never typed is a key never matched. What it must never do
is give a real word the wrong British form, which is why endings that
drop the extra letter (honorary, humorous, laborious, vaporise) are
generated by no group here.
"""

