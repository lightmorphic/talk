def _build():
    words = {}
    words.update(_grow(_OUR_STEMS, _OUR_ENDS, "or", "our"))
    words.update(_grow_end(_ISE_STEMS, _ISE_ENDS, "iz", "is"))
    words.update(_grow_end(_YSE_STEMS, _YSE_ENDS, "yz", "ys"))
    for group in (_RE, _LL, _ENCE, _OGUE, _AE, _ODD):
        words.update(group)
    # A word that is already British must never be a key, or the two
    # entries fight and the text changes on every pass.
    british = set(words.values())
    return {k: v for k, v in words.items() if k not in british}


BRITISH = _build()
