def _grow(stems, endings, old, new):
    """stem + ending, with `old` swapped for `new` on the British side."""
    out = {}
    for stem in stems:
        for end in endings:
            out[stem + end] = stem.replace(old, new) + end
    return out


def _grow_end(stems, endings, old, new):
    """As above, but the swap is in the ending rather than the stem."""
    out = {}
    for stem in stems:
        for end in endings:
            out[stem + end] = stem + end.replace(old, new)
    return out


